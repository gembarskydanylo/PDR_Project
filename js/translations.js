// t("key") або t("key", { n: 5 }) — підставляє {n} у рядок.
function t(key, vars) {
  const get = (lang) => key.split(".").reduce((v, p) => v?.[p], translations[lang]);
  let val = get(window.currentLang || "uk") ?? get("uk") ?? key;
  if (vars && typeof val === "string") {
    val = val.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  }
  return val;
}

// "12 питань" з правильною формою множини для поточної мови.
function plural(key, n) {
  const forms = t(key);
  if (typeof forms === "string") return `${n} ${forms}`;
  const cat = new Intl.PluralRules(window.currentLang || "uk").select(n);
  return `${n} ${forms[cat] ?? forms.other}`;
}

// Будь-яке поле з 4 мовами: { uk, nl, fr, en }.
function tr(obj) {
  return obj?.[window.currentLang] || obj?.uk || "";
}
